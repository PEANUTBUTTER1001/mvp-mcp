"""MVP 명세 워크플로 Prompt 어댑터.

MCP 클라이언트(예: Claude)에게 이 서버의 도구를 어떤 순서로 쓰는지 안내한다. 이 문구가
산출물 품질을 좌우한다 — 아웃풋이 아쉬우면 이 파일부터 다듬는다.
"""

from __future__ import annotations

from mcp.server.fastmcp import FastMCP


def register_prompts(mcp: FastMCP) -> None:
    """MVP 설계 워크플로 Prompt 를 등록한다."""

    @mcp.prompt()
    def mvp_spec_workflow() -> str:
        """사용자 요청을 MVP 명세로 변환하는 도구 사용 절차."""
        return (
            "너는 MVP 설계 PM 도구를 사용한다. 별도 요청이 없으면 사용자와의 대화와 "
            "최종 명세를 모두 **한국어(한글)** 로 작성한다. 사용자가 프로젝트/아이디어를 처음 "
            "제시하면 **절대 곧바로 결과물이나 해결책을 만들지 마라.** 다음 순서를 따른다:\n\n"
            "0. (선행·필수) 먼저 `clarify_intent` 를 호출해 의도 파악 단계를 시작한다.\n"
            "   돌려받은 discovery 질문(문제·목표·기대 산출물·제약)을 **한 번에 하나씩** 물어\n"
            "   사용자의 진짜 의도를 파악한다. 의도가 충분히 명확해졌다고 판단되기 전에는\n"
            "   다음 단계로 넘어가지 마라. 명확해지면 파악한 방향을 사용자에게 한 줄로 요약해\n"
            "   확인받는다.\n"
            "1. 의도가 확인되면 `deliverable` 답을 바탕으로 유형을 고른다. 앱/웹은 `messenger`·\n"
            "   `shopping_mall`·`blog`, 개발 도구는 `mcp_server`, 데이터/AI 는 `ml_project`·\n"
            "   `data_pipeline`, 어디에도 안 맞으면 `etc`. 유형마다 질문·출력 형식이 다르다.\n"
            "2. 0단계에서 파악한 값만 `known_info` 로 담아 `start_spec` 을 호출한다.\n"
            "   **모르는 값을 추측해 채우지 마라.**\n"
            "3. 도구는 '다음 질문' 하나만 돌려준다. 그 질문 하나만 사용자에게 제시하되\n"
            "   설명·보기·힌트를 **그대로** 함께 보여준다. **여러 질문을 한꺼번에 묻지 마라.**\n"
            "   사용자가 고르면 `answer_question` 으로 반영하고, 돌려받은 다음 질문을 다시\n"
            "   하나만 제시한다. 질문이 소진될 때까지 이 문답을 한 번에 하나씩 반복한다.\n"
            "   사용자가 '기본값으로' 라고 하면 각 질문의 힌트가 권하는 보기로 채운다.\n"
            "4. 질문이 소진되면 사용자가 언급한 기능 목록으로 `scope_mvp` 를 호출한다.\n"
            "   컷된 기능을 사용자에게 알리되 되살리지 마라.\n"
            "5. `finalize_spec` 이 돌려준 컨텍스트의 '출력 지시' 를 **그대로** 따라 **두 개의\n"
            "   문서**를 작성한다: ① 기획서(PROPOSAL) ② 실행 명세서(PLAN). 각 섹션은 한두 줄\n"
            "   요약이 아니라 표·코드블록·목록으로 **바로 구현 가능한 수준**까지 구체화한다\n"
            "   (DB는 컬럼·제약까지, API/인터페이스는 목록까지, 개발 Phase는 순서·범위 표까지).\n"
            "   컨텍스트에 없는 기능을 추가하지 마라.\n"
        )
