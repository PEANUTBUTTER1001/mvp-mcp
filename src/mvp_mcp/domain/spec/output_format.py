    lines.append("# MVP 프로젝트 명세 컨텍스트")
    lines.append("")
    lines.append("## 확정 정보")
    lines.append(f"- 프로젝트 유형: {display_name}")
    lines.append(f"- 원문 요청: {draft.user_request}")
    for key, label in _FIELD_LABELS.items():
        value = draft.answers.get(key)
        if value:
            lines.append(f"- {label}: {value}")

    lines.append("")
    lines.append("### 기술 스택")
    if draft.tech_stack:
        for key, value in draft.tech_stack.items():
            lines.append(f"- {key}: {value}")
    else:
        # 사용자가 "직접 지정"을 택함 → 서버가 스택을 추측하지 않는다.
        lines.append(
            "- 사용자가 기술 스택을 직접 지정하기로 함. 사용자가 제시한 스택을 반영하고, "
            "누락된 항목은 추측하지 말고 사용자에게 확인하라."
        )

    lines.append("")
    lines.append("## MVP 범위 (이 목록을 벗어난 기능을 추가하지 말 것)")
    included = ", ".join(draft.features) if draft.features else "(없음)"
    lines.append(f"- 포함: {included}")
    deferred = ", ".join(draft.deferred) if draft.deferred else "(없음)"
    lines.append(f"- 제외(11번 확장 계획에만 언급): {deferred}")

    lines.append("")
    lines.append("## 출력 지시")
    lines.append(
        "**모든 문서는 한국어(한글)로 작성하라.** 아래 **두 개의 문서**를 순서대로 작성하라: "
        "① 기획서(PROPOSAL) ② 실행 명세서(PLAN)."
    )
    lines.append(
        "각 섹션을 한두 줄로 뭉뚱그리지 말고, 표·코드블록·목록을 적극 사용해 **바로 구현에 "
        "착수할 수 있는 수준**으로 구체화하라. 두 문서는 명확히 구분해 작성한다."
    )

    lines.append("")
    lines.append("## 문서 1 — 기획서 (PROPOSAL)")
    lines.append("무엇을·왜 만드는지 이해시키는 상위 기획 문서.")
    for section in PROPOSAL_SECTIONS:
        lines.append(f"### {section}")
        proposal_guide = PROPOSAL_GUIDE.get(section)
        if proposal_guide:
            lines.append(proposal_guide)

    lines.append("")
    lines.append("## 문서 2 — 실행 명세서 (PLAN)")
    lines.append("문서 1을 바탕으로 바로 구현에 착수할 수 있는 상세 설계 문서.")
    for section in sections:
        lines.append(f"### {section}")
        section_guide = guide.get(section)
        if section_guide:
            lines.append(section_guide)

    lines.append("")
    lines.append("## 제약")
    lines.append("- 위 MVP 범위의 기능만 설계한다. 정보를 추측으로 채우지 않는다.")

    return "\n".join(lines)
